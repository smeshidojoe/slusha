"""Настройки бота-собеседника. Свой .env, свой токен, своя база.

Специально не тянем ничего из gremlin: это отдельный бот со своим процессом и
своими секретами. Общее у них только то, что лежит в одной папке проекта.
"""
import os

from dotenv import load_dotenv

PKG_DIR = os.path.dirname(os.path.abspath(__file__))
# папка, в которой лежит пакет: сюда же по умолчанию кладём data/ и лог.
# В образе это /app, а пакет — /app/slusha, как и монтирует docker-compose.
BASE_DIR = os.path.dirname(PKG_DIR)

load_dotenv(os.path.join(PKG_DIR, ".env"))

# Только свой токен: подхватить BOT_TOKEN модератора нельзя — два
# поллера на одном токене начнут отбирать апдейты друг у друга.
BOT_TOKEN = os.getenv("SLUSHA_BOT_TOKEN")

DB_PATH = os.getenv("SLUSHA_DB_PATH") or os.path.join(BASE_DIR, "data", "slusha.sqlite3")
LOG_PATH = os.getenv("SLUSHA_LOG_PATH") or os.path.join(BASE_DIR, "data", "slusha.log")

# Переписка чатов лежит отдельным файлом: пишется она на каждое сообщение,
# а настройки — раз в день, и мешать эти потоки в одной базе незачем. По
# умолчанию файл-сосед основной базы, поэтому тесты, подменившие SLUSHA_DB_PATH
# на временный, автоматически уводят туда и разговоры.
HISTORY_DB = (os.getenv("SLUSHA_HISTORY_DB")
              or DB_PATH.removesuffix(".sqlite3") + "_history.sqlite3")

try:
    ADMIN_IDS = {
        int(x) for x in (os.getenv("SLUSHA_ADMIN_IDS") or os.getenv("ADMIN_IDS")
                         or "").replace(" ", "").split(",") if x
    }
except ValueError as e:
    raise RuntimeError(f"ADMIN_IDS must be comma-separated integers: {e}") from e

TZ_OFFSET = int(os.getenv("TZ_OFFSET") or 3)

# Служебные аккаунты Telegram: это не люди, отвечать им незачем.
SERVICE_IDS = {777000, 1087968824, 136817688}

# Сообщение старше этого не трогаем: после простоя не отвечаем на вчерашнее.
MSG_MAX_AGE = 120

# ---------- модель ----------
#
# Провайдер: anthropic — родной SDK; openai — любой OpenAI-совместимый сервис
# (OpenRouter с Kimi и DeepSeek, Moonshot напрямую); ollama — локальная модель.
AI_PROVIDER = (os.getenv("AI_PROVIDER") or "anthropic").lower()
AI_KEY = os.getenv("ANTHROPIC_API_KEY") or ""
AI_BASE_URL = (os.getenv("AI_BASE_URL") or "").rstrip("/")
AI_API_KEY = os.getenv("AI_API_KEY") or ""
_DEFAULT_MODEL = {"anthropic": "claude-opus-5"}.get(AI_PROVIDER, "")
AI_MODEL = os.getenv("AI_MODEL") or _DEFAULT_MODEL

# Потолок токенов на ответ. Одним числом на все режимы он не работает: то, чего
# хватает на «коротко», обрывает «развёрнуто» на полуслове. Поэтому считаем его
# от выбранной длины ответа (AI_LEN_TOKENS ниже), а эта переменная — ручной
# override: задали в .env — действует она, не задали — считаем сами.
AI_MAX_TOKENS = int(os.getenv("AI_MAX_TOKENS") or 0)

# «Думающие» модели тратят токены на рассуждения и могут упереться в лимит,
# так и не начав отвечать. Просим их не думать вслух.
AI_NO_THINK = (os.getenv("AI_NO_THINK") or "1") not in ("0", "false", "no")
AI_THINKING_MODELS = ("qwen3", "qwq", "deepseek-r1", "magistral", "reasoning")

# Запас токенов там, где размышления выключить нельзя. У Claude Opus 5 они
# включены по умолчанию и тратят те же max_tokens: при лимите 800 модель
# успевала подумать и упиралась в потолок, так и не начав отвечать — в чат
# приходила пустота. Ответ по-прежнему режется по знакам, лишнее просто
# остаётся неиспользованным.
AI_THINKING_RESERVE = int(os.getenv("AI_THINKING_RESERVE") or 3000)

AI_MAX_CHARS = int(os.getenv("AI_MAX_CHARS") or 600)
AI_TIMEOUT = 40              # сек на запрос, дальше молчим
AI_COOLDOWN = 8              # пауза между ответами в одном чате, сек
AI_HISTORY = 200             # сколько сообщений чата держим в памяти
AI_PARTS = 3                 # на сколько сообщений максимум дробим ответ
AI_TYPING_CPM = 1200         # «скорость печати» для пауз между репликами
AI_PART_PAUSE_MAX = 5        # но ждать дольше этого не будем, сек

# сколько реплик уходит в промпт. В живом чате двадцать штук — это пара
# минут разговора, причём строки самого бота тоже занимают места
# Сколько реплик по умолчанию уходит в промпт новым чатам. Пятьдесят
# небольшая модель уже размазывает: вопрос тонет в чужом разговоре.
# С крупной моделью 50–80 читаются нормально, это дело настройки.
AI_CTX_DEFAULT = 30
AI_CTX_PRESETS = (10, 20, 30, 50, 80, 120)
AI_RANDOM_PRESETS = (0, 1, 3, 5, 10, 20, 50, 100)
# Шанс ответить на ответ себе. Сотня превращала разговор в пинг-понг:
# человек отвечает боту, бот обязательно отвечает человеку, тот снова
# боту — и чат занят ими двоими. Ноль — на реплаи не отвечать вовсе,
# зваться по имени бот всё равно продолжит.
AI_REPLY_PRESETS = (0, 10, 20, 35, 50, 75, 100)
AI_DAILY_PRESETS = (20, 50, 100, 200, 500, 1000, 3000, 10000)

# Температура. 0.9 давала на моделях 4B откровенную бессвязность: фразы
# грамматически целые, а мысль разваливается. 0.55–0.7 — рабочий коридор,
# в котором бот ещё не зануда, но уже держит нить.
AI_TEMPERATURE = float(os.getenv("AI_TEMPERATURE") or 0.6)

# Ollama по умолчанию даёт модели 4096 токенов и молча выбрасывает лишнее
# с начала промпта — то есть ровно характер. С карточкой на несколько тысяч
# знаков плюс лор плюс история этого мало, поэтому просим заметно больше.
# Плата — оперативка под KV-кэш, примерно вдвое против 8192.
AI_NUM_CTX = int(os.getenv("AI_NUM_CTX") or 16384)
# Штраф за повторы: маленькие модели любят копировать свои же прошлые ответы.
# Штраф за повторы. 1.2 оказался великоват для русского: морфология
# требует повторять корни, а штраф гонит модель за синонимами там, где
# их нет, и она начинает косноязычить. 1.05–1.1 — рабочий коридор.
AI_REPEAT_PENALTY = float(os.getenv("AI_REPEAT_PENALTY") or 1.1)

AI_LEN_PRESETS = (0, 1, 2)
AI_LEN_LABELS = {0: "коротко", 1: "средне", 2: "развёрнуто"}
AI_LEN_RULES = {
    0: ("одной-двумя короткими фразами", 400),
    1: ("двумя-тремя живыми фразами", 800),
    2: ("развёрнуто, 4–6 фраз, но без воды и списков", 1800),
}
# Потолок токенов под каждую длину. С запасом к потолку знаков: кириллица
# идёт примерно по три знака на токен, но у моделей с другим токенизатором
# бывает и полтора, а обрыв на полуслове хуже, чем неиспользованный лимит.
AI_LEN_TOKENS = {0: 400, 1: 700, 2: 1300}

# Язык ответа: 0 — как в чате, 1 — всегда русский, 2 — всегда английский.
# Настройка, а не константа: характер и лор часто английские, и без явного
# правила модель уходит на английский в русском чате — но бывают и чаты,
# где это ровно то, что нужно.
AI_LANG_PRESETS = (0, 1, 2)
AI_LANG_LABELS = {0: "как в чате", 1: "русский", 2: "английский"}
AI_LANG_RULES = {
    0: ("Отвечай на языке последней реплики собеседника. Характер и справка "
        "о мире могут быть написаны на другом языке — это материал для тебя, "
        "а не язык ответа."),
    1: ("Отвечай всегда по-русски. Характер и справка о мире могут быть "
        "написаны по-английски — это материал для тебя, а не язык ответа: "
        "имена и термины оттуда переноси в русский текст, но фразы строй "
        "русские."),
    2: "Always answer in English, whatever language the chat speaks.",
}

# ---------- шум ----------
#
# «ок», «ага», «+» и смайлик — это не повод будить модель. Отвечать на такое
# случайным броском значит выглядеть навязчивым: человек поддакнул, а бот
# влез с монологом. Прямое обращение и реплай боту к шуму не относятся —
# там отвечаем как обычно.
NOISE_MAX_LEN = 20           # короче этого и без слов из 4+ букв — шум
NOISE_DAMP = 10              # во столько раз режем случайный шанс на шуме

# ---------- долговременная память ----------
#
# Окно контекста помнит последние N реплик, всё старше пропадает бесследно.
# Раз в столько-то новых сообщений просим модель пересобрать заметки о чате:
# кто есть кто, о чём договорились, какие шутки прижились.
AI_SUMMARY_EVERY = int(os.getenv("AI_SUMMARY_EVERY") or 80)
AI_SUMMARY_LIMIT = int(os.getenv("AI_SUMMARY_LIMIT") or 2500)
AI_SUMMARY_TOKENS = int(os.getenv("AI_SUMMARY_TOKENS") or 1200)

# ---------- картинки ----------
#
# Фото уезжает в модель целиком, в base64: мегабайт картинки превращается
# примерно в полтора мегабайта запроса. Больше двух штук за раз незачем —
# это само сообщение и то, на которое отвечают.
AI_IMAGE_MAX_BYTES = int(os.getenv("AI_IMAGE_MAX_BYTES") or 4 * 1024 * 1024)
AI_IMAGE_MAX = 2

# ---------- ветка реплаев ----------
#
# Telegram отдаёт только одно родительское сообщение: вложенных в нём нет.
# Ветку восстанавливаем сами по своей истории, поднимаясь вверх по reply_to.
REPLY_CHAIN_DEPTH = 4

# Потолок характера. Стоит с запасом: карточки с chub редко бывают длиннее,
# так что обрезать обычно нечего. Помните только, что характер уезжает в модель
# на каждый запрос и делит окно контекста с историей чата и лором: 8000 знаков
# кириллицы — это примерно 3000 токенов из AI_NUM_CTX.
AI_PERSONA_LIMIT = int(os.getenv("AI_PERSONA_LIMIT") or 8000)
# А это рекомендуемая длина, при превышении которой меню начинает
# ворчать. Карточки с chub пишут под ролевые модели с большим окном и
# длинным отыгрышем; в болтовне характер на пять тысяч знаков занимает
# половину промпта, и вопрос собеседника в нём тонет. Внешность,
# биография и таблицы атрибутов на реплику в чате не влияют вовсе.
AI_PERSONA_SOFT = int(os.getenv("AI_PERSONA_SOFT") or 2000)

# Примеры реплик персонажа из карточки (mes_example). Строк берём
# немного: это образец манеры, а не второй лорбук.
AI_EXAMPLE_LINES = int(os.getenv("AI_EXAMPLE_LINES") or 6)
AI_EXAMPLE_LIMIT = int(os.getenv("AI_EXAMPLE_LIMIT") or 1200)

LORE_BUDGET = int(os.getenv("LORE_BUDGET") or 1500)
LORE_LIMIT = 200

# ---------- веб-панель ----------
#
# То же самое, что инлайн-меню, но страницей: список чатов не листается по
# восемь штук, характер видно целиком, лорбук правится без диалога с ботом.
# Живёт в том же процессе — ей нужны та же база и тот же объект Bot.
# Наружу порт выводит туннель (ngrok, cloudflared): мини-приложение Telegram
# открывает только по https, а заводить сертификат ради одной страницы незачем.
WEB_ENABLED = (os.getenv("SLUSHA_WEB") or "0") not in ("0", "false", "no")
WEB_HOST = os.getenv("SLUSHA_WEB_HOST") or "0.0.0.0"
WEB_PORT = int(os.getenv("SLUSHA_WEB_PORT") or 8082)
# Публичный https-адрес панели. Пустой — кнопки в меню не будет: Telegram
# откроет мини-приложение только по нему, локальный порт ему недоступен.
WEBAPP_URL = (os.getenv("SLUSHA_WEBAPP_URL") or "").rstrip("/")
# Сколько живёт подпись initData. Старую могли подсмотреть в логах туннеля.
WEB_INITDATA_TTL = int(os.getenv("SLUSHA_WEB_TTL") or 24 * 3600)
WEB_UPLOAD_MAX = 5 * 1024 * 1024

