"""Как каждый человек обращается с ботом — чтобы отвечать каждому по-своему.

Без этого тон ответа задаёт переписка, а не собеседник. Один человек
полчаса поливает бота матом, бот огрызается, и дальше огрызается уже на всех:
грубые реплики лежат в окне контекста и тянут за собой следующий ответ. На
замере с Холо вежливый вопрос «как у тебя настроение?» после такой перепалки
получал «Ненавижу вопросы!» и «если ты не слишком тупишь».

Поэтому считаем по каждому человеку, сколько грубостей и добрых слов он
адресовал боту, и перед ответом говорим модели, с кем она разговаривает:
- кто часто грубит — с тем холодно и колко, но по делу;
- с остальными — по-дружески, в своём характере, что бы ни творилось в чате.

Почему так:
- Считаем только обращения к боту — реплай на него или имя в тексте. Мат
  между людьми в чате — их дело, к боту он отношения не имеет.
- Словарь, а не модель. Судить каждую реплику моделью — лишний запрос на
  каждое сообщение. Ошибка словаря здесь дешёвая: она меняет одну строку
  промпта, а не решает, отвечать ли вообще.
- Счёт затухает: грубость недельной давности не повод держать человека в
  чёрном списке вечно. Полураспад — HALF_LIFE.
- Строку для вежливых пишем всегда, а не только для грубиянов. Без неё
  заражение тоном из переписки остаётся как было. Замер на трёх живых
  перепалках, по три прогона: Холо огрызалась на вежливый вопрос в 6 ответах
  из 18, со строкой — в 2–3; грубияну вместо «Заткнись» отвечала холодно и
  без мата. Яни на «как настроение?» стала спрашивать в ответ, Коул остался
  таким же язвой — характер строка не ломает.
"""
import logging
import re
import time

logger = logging.getLogger("slusha.mood")

# За сколько секунд счёт уменьшается вдвое.
HALF_LIFE = 3 * 24 * 3600
# С какого счёта человек считается грубияном: две свежие грубости, или
# три-четыре за последнюю неделю.
RUDE_AT = 1.5

# Оскорбления, адресованные собеседнику, а не мат вообще: «бля, смешно» —
# это не грубость боту. Проверено на живых обращениях к трём ботам.
_RUDE = re.compile(r"""(?ix)
 \bтуп(ая|ой|ица|орыл\w*|ое)\b | \bдур(а|ак|очка|ында)\b | идиот | дебил | \bдаун\b
 | долбо[её]б | \bеблан | у[её]б(ок|ище|ан\w*) | \bмудак | \bмудил | \bшлюх | \bсучк
 | \bты\s+(\w+\s+)?(сука|говно|тварь|мразь|чмо|лох|клоун|урод|овощ|ничтожество
                    |бесполезн\w*|жалк\w*|никчемн\w*|никчёмн\w*)
 | говно\s*(бот|ии|нейронк\w*) | (бот|ии|нейронка)\s+(говно|тупо?й|тупая|ебан\w*)
 | хуйн[яюи]\s+(ебуч\w*|иишн\w*|тупая|нес\w*|пиш\w*|гониш\w*|городиш\w*)
 | заткнись | завали\s*(сь|ебало|еблет|рот|пиздак|хлебало|ебальник)
 | ебало\s+(завали|закрой|стяни) | \bсоси\b
 | (иди|пош[её]л|пошла|катись|вали)\s+(ты\s+)?(на\s?хуй|в\s+(жопу|пизду|очко)|нахер|отсюда)
 | нахуй\s+(иди|пош[её]л|пошла) | от[ъь]ебись | съеби(сь)?\b | у[её]бывай | \bотвали\b
 | \bпидор | \bпидр | \bчмо\b | \bмразь | \bтварь | \bгнида | \bскотин | \bпадл[аы]
 | \bурод\b | \bуродин | \bсдохни | ненавижу\s+тебя | \bкончен(ая|ый|ная)
 | \bебанут\w* | \bебан(ая|ый)\b | \bлох\b | \bлошар
 | тебя\s+(щас\s+|сейчас\s+)?(убью|урою|выебу|въебу|отпизжу|прибью|сожгу)
 | в\s+газовую\s+камеру
""")

_KIND = re.compile(r"""(?ix)
 \bспасиб\w* | \bспс\b | \bблагодар\w* | люблю\s+тебя | обожаю\s+тебя
 | \bумни(ца|чка) | \bмолодец | \bмолодчин\w*
 | \bты\s+(такая\s+|такой\s+|самая\s+|самый\s+)?(хорош\w*|мил\w*|лапочк\w*|солнышк\w*
                                               |прелесть|умн\w*|лучш\w*|зайк\w*|котик\w*)
 | \bобнима\w* | \bобнял\w* | \bцелую\b | \bкрасава | \bреспект
 | ❤ | 💕 | 🥰 | 😘 | 💖 | 🤗
""")


def tone(text: str) -> int:
    """-1 — грубость, 1 — доброе слово, 0 — ни то ни другое.

    Грубость перевешивает: «спасибо, тупая железка» — всё-таки грубость.
    """
    if _RUDE.search(text or ""):
        return -1
    if _KIND.search(text or ""):
        return 1
    return 0


def _decay(value: float, since: int, now: int) -> float:
    return value * 0.5 ** (max(0, now - since) / HALF_LIFE)


async def note(chat_id: int, who: str, text: str) -> None:
    """Учесть реплику, адресованную боту. Нейтральные счёт не трогают."""
    from . import history as store
    t = tone(text)
    if not t:
        return
    now = int(time.time())
    try:
        old = await store.mood_get(chat_id, who)
        rude, kind = ((_decay(old[0], old[2], now), _decay(old[1], old[2], now))
                      if old else (0.0, 0.0))
        if t < 0:
            rude += 1
        else:
            kind += 1
        await store.mood_set(chat_id, who, rude, kind)
    except Exception:
        logger.warning("не учесть тон %s в чате %s", who, chat_id, exc_info=True)


def rude(score) -> bool:
    """Грубиян ли — по счёту (грубость, доброта, когда), уже с учётом затухания."""
    if not score:
        return False
    now = int(time.time())
    r, k = _decay(score[0], score[2], now), _decay(score[1], score[2], now)
    return r >= RUDE_AT and r >= k


async def line(chat_id: int, who: str) -> str:
    """Строка для задания: как этот человек обращается с ботом и как с ним говорить.

    Без «не»: маленькая модель запрет читает как подсказку.
    """
    from . import history as store
    try:
        score = await store.mood_get(chat_id, who)
    except Exception:
        logger.warning("не прочитать тон %s в чате %s", who, chat_id, exc_info=True)
        return ""
    if rude(score):
        return (f"{who} часто грубит тебе. С ним ты держишься прохладно и колко: "
                "коротко ставишь на место и отвечаешь по делу.")
    return (f"{who} общается с тобой по-доброму. С ним разговор дружеский: "
            "отвечаешь тепло, в своём характере.")
